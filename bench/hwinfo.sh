#!/usr/bin/env bash
# Regenerate docs/hardware.md for the machine this runs on.
#
# Records lscpu, nproc, free -h, nvidia-smi, nvcc --version, mpirun --version and
# gcc --version, the DRAM configuration and the theoretical/measured bandwidth ceilings.
# Run bench/stream.sh first so the STREAM Triad number is included.
#
# DRAM details need dmidecode, which needs root. Either run `sudo dmidecode -t memory`
# yourself and pass what it shows, or leave them out and the file keeps a TODO:
#   DRAM_TYPE=DDR5 DRAM_MTS=4800 DRAM_CHANNELS=8 bench/hwinfo.sh
# GPU spec bandwidth (vendor GB/s, from the datasheet): GPU_SPEC_GBS=936 bench/hwinfo.sh
# DRAM_SOURCE / GPU_SPEC_SOURCE say where the numbers came from.
set -uo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
HOST=$(hostname -s 2>/dev/null || hostname)
OUT=${OUT:-$ROOT/docs/hardware.md}
STREAM_TXT=$ROOT/bench/results/stream_$HOST.txt
mkdir -p "$(dirname "$OUT")"

cmd_block() { # title command...
  local title=$1
  shift
  echo "### \`$*\`"
  echo
  echo '```'
  if command -v "$1" >/dev/null 2>&1; then
    "$@" 2>&1 | sed -e 's/[[:space:]]*$//'
  else
    echo "$1: not installed on this machine"
  fi
  echo '```'
  echo
}

# Try dmidecode without sudo (works only if already permitted).
if [[ -z ${DRAM_MTS:-} ]] && command -v dmidecode >/dev/null 2>&1; then
  dmi=$(dmidecode -t memory 2>/dev/null || true)
  if [[ -n $dmi ]]; then
    DRAM_TYPE=${DRAM_TYPE:-$(awk -F': ' '/^\s*Type: DDR/ { print $2; exit }' <<<"$dmi")}
    DRAM_MTS=$(awk -F': ' '/Configured Memory Speed: [0-9]/ { print $2 + 0; exit }' <<<"$dmi")
    DRAM_CHANNELS=${DRAM_CHANNELS:-$(grep -cE '^\s*Size: [0-9]+ [GM]B' <<<"$dmi")}
    DRAM_SOURCE=${DRAM_SOURCE:-"dmidecode -t memory (populated DIMMs counted as channels; check against the board manual)"}
  fi
fi

gib() { awk -v x="$1" 'BEGIN { printf "%.1f", x }'; }

cpu_model=$(lscpu | awk -F': *' '/^Model name/ { print $2; exit }')
sockets=$(lscpu | awk -F': *' '/^Socket\(s\)/ { print $2; exit }')
cores_per_socket=$(lscpu | awk -F': *' '/^Core\(s\) per socket/ { print $2; exit }')
numa=$(lscpu | awk -F': *' '/^NUMA node\(s\)/ { print $2; exit }')
llc=$(lscpu | awk -F': *' '/^L3 cache/ { print $2; exit }')
mem_total=$(free -h | awk '/^Mem:/ { print $2 }')
flags=$(lscpu | awk -F': *' '/^Flags/ { print $2 }')
simd=""
for f in avx2 avx512f avx512bw avx512vl; do [[ " $flags " == *" $f "* ]] && simd+="$f "; done

if [[ -n ${DRAM_MTS:-} && -n ${DRAM_CHANNELS:-} ]]; then
  cpu_theory=$(awk -v m="$DRAM_MTS" -v c="$DRAM_CHANNELS" 'BEGIN { printf "%.1f", m * 1e6 * 8 * c / 1024^3 }')
  cpu_theory_line="${DRAM_MTS} MT/s x 10^6 x 8 B x ${DRAM_CHANNELS} ch / 1024^3 = **${cpu_theory} GiB/s**"
  dram_line="${DRAM_TYPE:-DDR?}-${DRAM_MTS}, ${DRAM_CHANNELS} channel(s) (source: ${DRAM_SOURCE:-given by hand})"
else
  cpu_theory=""
  cpu_theory_line="TODO: needs DRAM speed and channel count"
  dram_line="TODO(Person A): run \`sudo dmidecode -t memory\` and rerun as \`DRAM_TYPE=.. DRAM_MTS=.. DRAM_CHANNELS=.. bench/hwinfo.sh\`"
fi

triad=""
if [[ -s $STREAM_TXT ]]; then
  triad=$(awk '/^Triad:/ { printf "%.1f", $2 * 1e6 / 1024^3; exit }' "$STREAM_TXT")
  stream_cfg=$(head -1 "$STREAM_TXT")
fi

gpu_name=""
if command -v nvidia-smi >/dev/null 2>&1; then
  gpu_name=$(nvidia-smi --query-gpu=name --format=csv,noheader 2>/dev/null | head -1)
fi
if [[ -n ${GPU_SPEC_GBS:-} ]]; then
  gpu_theory=$(awk -v g="$GPU_SPEC_GBS" 'BEGIN { printf "%.1f", g * 1e9 / 1024^3 }')
  gpu_theory_line="${GPU_SPEC_GBS} GB/s x 10^9 / 1024^3 = **${gpu_theory} GiB/s** (source: ${GPU_SPEC_SOURCE:-vendor datasheet})"
elif [[ -n $gpu_name ]]; then
  gpu_theory_line="TODO(Person A): look up the datasheet memory bandwidth for ${gpu_name} and rerun with GPU_SPEC_GBS=.."
else
  gpu_theory_line="n/a: no NVIDIA GPU on this machine"
fi

{
  echo "# Hardware: $HOST"
  echo
  echo "Generated by \`bench/hwinfo.sh\` on $(date -u +%Y-%m-%d) (UTC), commit $(git -C "$ROOT" rev-parse --short HEAD 2>/dev/null || echo none)."
  echo "Rerun it on the testbed; it overwrites this file. All bandwidths are base-1024 GiB/s"
  echo "(vendor GB/s x 0.931)."
  echo
  echo "## Summary"
  echo
  echo "| | |"
  echo "|---|---|"
  echo "| CPU | ${cpu_model} (${sockets} socket(s) x ${cores_per_socket} cores, $(nproc) hardware threads) |"
  echo "| NUMA nodes | ${numa:-?} |"
  echo "| Last-level cache | ${llc:-?} |"
  echo "| SIMD (from lscpu flags) | ${simd:-none of avx2/avx512} |"
  echo "| Memory | ${mem_total} visible to the OS |"
  echo "| DRAM | ${dram_line} |"
  echo "| GPU | ${gpu_name:-none (no nvidia-smi)} |"
  echo
  echo "## Bandwidth ceilings"
  echo
  echo "| Ceiling | GiB/s | How |"
  echo "|---|---:|---|"
  echo "| CPU theoretical | ${cpu_theory:-TODO} | ${cpu_theory_line} |"
  if [[ -n $triad ]]; then
    echo "| CPU measured, STREAM Triad | ${triad} | bench/stream.sh: ${stream_cfg} |"
  else
    echo "| CPU measured, STREAM Triad | TODO | run bench/stream.sh, then rerun this script |"
  fi
  if [[ -n $cpu_theory && -n $triad ]]; then
    echo "| STREAM / theoretical | $(awk -v a="$triad" -v b="$cpu_theory" 'BEGIN { printf "%.0f%%", 100 * a / b }') | |"
  fi
  echo "| GPU theoretical | ${gpu_theory:-n/a} | ${gpu_theory_line} |"
  echo "| GPU measured, device copy kernel | TODO(Person C) | step 5 adds the copy kernel |"
  echo
  echo "## Raw command output"
  echo
  cmd_block lscpu lscpu
  cmd_block nproc nproc
  cmd_block free free -h
  cmd_block nvidia-smi nvidia-smi
  cmd_block nvcc nvcc --version
  cmd_block mpirun mpirun --version
  cmd_block gcc gcc --version
  cmd_block cmake cmake --version
  if [[ -s $STREAM_TXT ]]; then
    echo "### STREAM output (bench/results/stream_$HOST.txt)"
    echo
    echo '```'
    cat "$STREAM_TXT"
    echo '```'
  fi
} >"$OUT"

echo "wrote $OUT" >&2
